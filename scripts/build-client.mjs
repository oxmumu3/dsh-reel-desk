// Assembles client.js from shared/kinds.js + shared/composition-core.js + src-client/panel-body.js
// so the browser player, conversation cards, and the Remotion 4 MP4/GIF renderer share the exact same
// scene definitions, f(frame) physics, & React scene tree, with ZERO ESM `export` statements in client.js.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')

const stripExports = src => src
  .replace(/^export\s+function\s+/gm, 'function ')
  .replace(/^export\s+const\s+/gm, 'const ')

const kindsSrc = stripExports(fs.readFileSync(path.join(rootDir, 'shared', 'kinds.js'), 'utf8'))
const sharedSrc = stripExports(fs.readFileSync(path.join(rootDir, 'shared', 'composition-core.js'), 'utf8'))
const panelBody = fs.readFileSync(path.join(rootDir, 'src-client', 'panel-body.js'), 'utf8')

const banner = [
  '// @oxmumu3/dsh-reel-desk — Browser client bundle (generated by scripts/build-client.mjs).',
  '// Wrapped in window.__ModuleLoader__.load; zero ESM export statements.',
  '',
  'window.__ModuleLoader__.load({',
  "  id: '@oxmumu3/dsh-reel-desk',",
  '  factory: (require) => {',
  "    'use strict'",
  '    var module = { exports: {} }',
  '    var exports = module.exports',
  '',
].join('\n')

const footer = [
  '',
  '    return module.exports',
  '  },',
  '})',
  '',
].join('\n')

const output = `${banner}${kindsSrc}\n${sharedSrc}\n${panelBody}${footer}`

if (/^\s*export\s+/m.test(output)) {
  throw new Error('client.js still contains ESM export statement!')
}

fs.writeFileSync(path.join(rootDir, 'client.js'), output, 'utf8')
console.log(`Built client.js (${Buffer.byteLength(output, 'utf8')} bytes)`)
